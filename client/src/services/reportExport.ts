import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

export interface ExportableReport {
  callerNumber: string;
  peakRiskScore: number;
  scamType: string;
  summary: string;
  redFlags: string[];
  formalComplaintText: string;
  investigationStatus?: string;
  investigatorNotes?: string;
  reviewedBy?: string;
  reviewedAt?: string;
  createdAt?: number | string | Date;
}

// ── PDF Export ──
export const exportToPDF = (report: ExportableReport) => {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 20;

  // Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('CYBER CRIME INCIDENT REPORT', pageWidth / 2, y, { align: 'center' });
  const titleWidth = doc.getTextWidth('CYBER CRIME INCIDENT REPORT');
  doc.setLineWidth(0.5);
  doc.line((pageWidth - titleWidth) / 2, y + 2, (pageWidth + titleWidth) / 2, y + 2);
  y += 15;

  // Incident Details Table
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('Complaint / Incident Details', 14, y);
  y += 5;

  autoTable(doc, {
    startY: y,
    theme: 'grid',
    styles: { fontSize: 10, cellPadding: 3, textColor: [0, 0, 0], lineColor: [0, 0, 0], lineWidth: 0.1 },
    headStyles: { fillColor: [240, 240, 240], fontStyle: 'bold', textColor: [0, 0, 0] },
    columnStyles: { 0: { fontStyle: 'bold', cellWidth: 70 }, 1: { cellWidth: 'auto' } },
    body: [
      ['Date Reported', new Date(report.createdAt || Date.now()).toLocaleString()],
      ['Suspect Caller Number', report.callerNumber],
      ['Category', 'Online Financial Fraud / Scams'],
      ['Sub-Category', report.scamType],
      ['AI Risk Score', `${report.peakRiskScore}/100`],
      ['Investigation Status', report.investigationStatus || 'Pending'],
      ['Reviewed By', report.reviewedBy || '—'],
    ],
  });
  y = (doc as any).lastAutoTable?.finalY ? (doc as any).lastAutoTable.finalY + 10 : y + 50;

  // Red Flags
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('Detected Red Flags', 14, y);
  y += 5;

  autoTable(doc, {
    startY: y,
    theme: 'grid',
    styles: { fontSize: 10, cellPadding: 3, textColor: [0, 0, 0], lineColor: [0, 0, 0], lineWidth: 0.1 },
    head: [['#', 'Red Flag']],
    headStyles: { fillColor: [240, 240, 240], fontStyle: 'bold', textColor: [0, 0, 0] },
    columnStyles: { 0: { fontStyle: 'bold', cellWidth: 15 }, 1: { cellWidth: 'auto' } },
    body: report.redFlags.map((flag, i) => [`${i + 1}`, flag]),
  });
  y = (doc as any).lastAutoTable?.finalY ? (doc as any).lastAutoTable.finalY + 10 : y + 30;

  // Summary
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('Incident Summary', 14, y);
  y += 6;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  const summaryLines = doc.splitTextToSize(report.summary || 'No summary available.', pageWidth - 28);
  doc.text(summaryLines, 14, y);
  y += summaryLines.length * 5 + 10;

  // Investigation Notes
  if (report.investigatorNotes) {
    if (y > 240) { doc.addPage(); y = 20; }
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.text('Investigator Notes', 14, y);
    y += 6;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    const notesLines = doc.splitTextToSize(report.investigatorNotes, pageWidth - 28);
    doc.text(notesLines, 14, y);
    y += notesLines.length * 5 + 10;
  }

  // Formal Complaint
  if (y > 230) { doc.addPage(); y = 20; }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('Formal Complaint Text (For Police FIR)', 14, y);
  y += 6;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  const complaintLines = doc.splitTextToSize(report.formalComplaintText || 'No complaint text generated.', pageWidth - 28);
  let remaining = [...complaintLines];
  while (remaining.length > 0) {
    const space = 280 - y;
    const fit = Math.floor(space / 5);
    if (fit <= 0) { doc.addPage(); y = 20; continue; }
    doc.text(remaining.slice(0, fit), 14, y);
    remaining = remaining.slice(fit);
    if (remaining.length > 0) { doc.addPage(); y = 20; }
  }

  // Footer on every page
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(8);
    doc.text(`Generated by Dhwani AI - Page ${i} of ${pages}`, pageWidth / 2, 290, { align: 'center' });
  }

  doc.save(`Dhwani_AI_Investigation_${report.callerNumber}.pdf`);
};

// ── CSV Export ──
export const exportToCSV = (reports: ExportableReport[]) => {
  const headers = ['Caller Number', 'Peak Risk', 'Scam Type', 'Status', 'Reviewer', 'Summary', 'Red Flags', 'Notes'];
  const rows = reports.map((r) => [
    r.callerNumber,
    String(r.peakRiskScore),
    r.scamType,
    r.investigationStatus || 'Pending',
    r.reviewedBy || '',
    `"${(r.summary || '').replace(/"/g, '""')}"`,
    `"${r.redFlags.join('; ')}"`,
    `"${(r.investigatorNotes || '').replace(/"/g, '""')}"`,
  ]);

  const csv = [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `Dhwani_AI_Cases_${new Date().toISOString().slice(0, 10)}.csv`;
  a.click();
  URL.revokeObjectURL(url);
};

